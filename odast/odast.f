      PROGRAM ODAST 
C     THIS PROGRAM EVALUATES THE ONE DIMENSIONAL ANALYTICAL
C     SOLUTE TRANSPORT SOLUTION CONSIDERING CONVECTION,
C     DISPERSION, DECAY AND ADSORPTION.
C     NUMX    =   NUMBER OF X POSITIONS
C     NUMT   =    NUMBER OF TIMES
C     X            =   DISTANCES FROM THE SOURCE (METERS)
C     T            =   TIME ELAPSED SINCE THE BEGINNING OF
C                      OPERATION (YEARS)
C     D1        =    COEFFICIENT OF DISPERSION (M*M/DAY)
C     V1        =     PORE WATER VELOCITY (M/DAY)
C     R           =     RETARDATION FACTOR
C     T0         =     THE TOTAL PERIOD OF WASTE RECHARGE (YEARS)
C     ALAM1   =    DECAY FACTOR OF THE SOLUTE (1/DAY)
C     ALFA1    =   DECAY FACTOR OF THE SOURCE (1/DAY)
      DOUBLE PRECISION    X, T, CD, PI, D1, V1, R, T0, ALAM1, ALFA1
     1, V,D,ALAM, ALFA,T1, X1, DSQRT2, U,C1,C2, B1, B2, B3, C3,
     2 A1, A, BB1, BB2, DD2, CC1, CC2, DD, DD1, A2, ARG
     
      DOUBLE PRECISION EXER, EXPD
      
      DIMENSION CD(6), X(100), T(100)
      DATA IXE, MINUS/2HX=,1H-/
      
      CHARACTER(30)OUTPUT_FILE_NAME,INPUT_FILE_NAME
      
      INPUT_FILE_NAME  = "INPUT.TXT"
      OUTPUT_FILE_NAME = "OUTPUT.TXT"
      
      PRINT*,"PROGRAM READ INPUT DATA FROM ",INPUT_FILE_NAME
      PRINT*,"PROGRAM WRITES OUTPUT TO ",OUTPUT_FILE_NAME
      
      OPEN(UNIT=8, FILE = INPUT_FILE_NAME)
      OPEN(UNIT=7, FILE = OUTPUT_FILE_NAME)
      
      PI=4*DATAN(1.0D0)
      !print*,"START ENTER NUMX,NUMT"
      READ(8,510) NUMX, NUMT
      print*,"NUMX = ",NUMX," NUMT = ",NUMT
      !print*,"Enter ",NUMX," number of  X values"
      !READ(8,520) (X(I),I=1,NUMX)
      READ(8,*) (X(I),I=1,NUMX)
      WRITE(6,*)"X DATA READ ",X(1)," ",X(NUMX)
      !print*,"Enter ",NUMT," number of  T values"
      !READ(8,520) (T(I),I=1,NUMT)
      READ(8,*) (T(I),I=1,NUMT)
      WRITE(6,*)"T DATA READ ",T(1)," ",T(NUMT)
 !10   !print*,"Enter D1, V1, R, T0, ALAM1, ALFA1"     
 !10   READ(8,520) D1, V1,R, T0, ALAM1, ALFA1
 10   WRITE(6,*)"ABOUT TO READ 6 NUMBERS"
      READ(8,*) D1, V1, R, T0, ALAM1, ALFA1
 !10   READ(8,*) D1, V1, R, T0, ALAM1, ALFA1
      WRITE(6,*)"6 VALUES READ",D1,V1,R,T0,ALAM1,ALFA1
      IF (D1 .EQ. 0.) STOP
      V=V1*365.25
      D=D1*365.25
      ALAM= ALAM1*365.25
      ALFA= ALFA1*365.25
      DO 90 IX = 1,NUMX, 6
      LX=MIN0(IX+5,NUMX)
      IP=MAX0(2-IX,0)
      WRITE(7,610) IP, V1, D1, R, ALAM1, ALFA1, T0, (IXE, X(I),I=IX, LX)
      WRITE(7,620) (MINUS,I=IX, LX)
      DO 80 II= 1,NUMT
      T1=T(II)
      K1=0
      DO 70 KK=IX, LX
      K1=K1+1
      X1=X(KK)
      IFLAG=0
 20   IF (ALFA.EQ.ALAM) GO TO 30
      DSQRT2=2* DSQRT(D*R*T1)
      U=DSQRT(V*V+4*D*R*(ALAM-ALFA))
      C1=X1*(V-U)/(2*D)
      C2=X1* (V+U)/(2*D)
      B1= (R*X1-U*T1)/DSQRT2
      B2= (R*X1+U*T1)/DSQRT2
      B3= (R*X1+V*T1)/DSQRT2
      C3=(V*X1/D)+(ALFA-ALAM)*T1
      A1= (V/(V+U))* EXER(C1,B1)+(V/(V-U))*EXER(C2, B2)+
     1        (V*V/(2*D*R*(ALAM-ALFA)))*EXER(C3,B3)
      A=A1
      GO TO 40
 30   DSQRT2=2*DSQRT(D*R*T1)
      BB1= (R*X1-V *T1)/DSQRT2
      BB2=V*X1/D
      DD2 = DSQRT(V*V*T1/(PI*D*R))
      CC1 =BB1* BB1
      CC2= (R*X1 +V*T1)/DSQRT2 
      DD=1.+(V*X1/D)+(V*V*T1/(D*R))
      DD1=0.0
      A2=0.5*EXER(DD1,BB1)+DD2 *EXPD(-CC1)-0.5*DD* EXER(BB2,CC2)
      A=A2
 40   IF (IFLAG .EQ. 1) GO TO 50 
      ARG=-T1* ALFA
      CD(K1) =EXPD(ARG) *A
      IF (T1 .LE. T0) GO TO 60 
      T1=T1-T0
      IFLAG=1
      GO TO 20
 50   CD(K1) =CD(K1)-A* EXPD(-ALFA*T(II))
      T1=T(II)
 60   IF (CD(K1) .LT. 1.E-14) CD(K1)=0.
 70   CONTINUE 
      WRITE(7,630) T(II),(CD(KK), KK=1,K1)
 80   CONTINUE
 90   CONTINUE
 
      GO TO 10
      
 510  FORMAT(2I5)
 520  FORMAT(6D10.4)
 610  FORMAT(//I1,20X, 36HDIMENSIONLESS CONCENTRATION C/CO FOR
     1/1H0,7X,2HV=,F6.2,2X,2HD=,F6.2,2X,2HR=,F3.1,2X,7HLAMBDA=
     2 ,F5.3,2X,6HALPHA=,F5.3,
     3 2X,3HT0=,F5.1/8X,61(1H-)/,9H T(YEARS),6(4X,A2,F5.0))
 620  FORMAT(1X, 10(1H-),6( A1,10(1H-)))
 630  FORMAT(3X,F5.1,2X,6D11.4)
 
      CLOSE(UNIT=7)
      CLOSE(UNIT=8)
      END

      DOUBLE PRECISION FUNCTION EXER (A,B)
C     THIS SUBROUTINE IS FROM VAN GENUCHTEN AND ALVES (1982)
C
C     PURPOSE.. TO CALCULATE EXP(A) *ERFC(B)
C
      DOUBLE PRECISION EXPD
      DOUBLE PRECISION A,B,C,X,T,Y 
      
      !EXER = DEXP(A)*ERFC(B)
      !RETURN
      
      EXER=0.0
      IF ((DABS(A).GT.170.).AND.B.LE.0.) RETURN
      IF (B.NE.0.0) GO TO 100
      EXER=EXPD(A)
      RETURN
 100  C=A-B*B
      IF ((DABS(C) .GT. 170.).AND. (B.GT.0)) RETURN
      IF (C .LT. -170.) GO TO 130
      X=DABS(B)
      IF (X .GT. 3.0) GO TO 110
      T=1./(1.+.3275911*X)
      Y=T*(.2548296-T*(.2844967-T*(1.421414-T*(1.453152-1.061405*T)))) 
      GO TO 120
 110  Y=.5641896/(X+.5/(X+1./(X+1.5/(X+2./(X+2.5/(X+1.))))))
 120  EXER =Y*EXPD(C)
 130  IF (B .LT. 0.0) EXER=2* EXPD(A)-EXER
      RETURN
      END



      DOUBLE PRECISION FUNCTION EXPD(X)
C
C     THIS IS THE DOUBLE PRECISION EXPONENTIAL FUNCTION 
C     EXCEPT THAT ARGUMENTS LESS THAN -170 IMPLY A VALUE 
C     OF 0. THIS IS TO PREVENT AN ERROR MESSAGE IN DEXP
C
      DOUBLE PRECISION   X
      EXPD=0.0
      IF (X.LT.-170) RETURN
      EXPD=DEXP(X)
      RETURN
      END
