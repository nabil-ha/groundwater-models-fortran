      END


!C SUBROUTINE NSCONT
      SUBROUTINE NSCONT (HA,HTA,HTM,ZA,ZM,CRXA,CRXM,CRL)
!C
!C
!C          THIS SUSROUTINE TPANSFERS THE COEFFICIENTS, MLLTIPLIED BY THEIR
!C           PESPECTIVE H-VALUE, TO THE RIGHT HAND SIDE VECTOR MATRIX IN
!C           CASE OF ADJACENT CONSTANT HEAD OR KNOWN BCUADARY                       CONDITIONS.
!C           IT ALSO SETS COEFFICIENTS EQUAL TO ZERC IN CASE OF ADJACENT 
!C            IMPERMEARLE BCUNDARIES.
!C
      IF (HA.LT.20000.0) GO TO 110
      CRL=CRL-CRXA*HTA
      CRXM= CRXM-CRXA
      CRXA=0.0
      GO TO 120
 110  IF (HA.GE.10000.0) GO TO 130
 120  IF ((HTM-ZM) .LE.1.0.AND.HTM.GT.HTA ) GO TO 130
      IF ((HTA-ZA).GT.1.0.OR.HTA.LE.HTM) GO TO 140
 130  CRXA=0.0
!C
 140  RETURN
!C
      END


!C SUBROUTINE BJUST
      SUBROUTINE BJUST (NR,NC,H,HT,HP, DX,DY,I)
!C
!C
!C           THIS SUPROUTINE ADJUSTS THE UNDERFLOW BOUNDARY WATER TABLE OR
!C          HEAD ELFVATICNS. BOUNDARY ELEVATIONS ARE HELD CONSTANT FOR
!C          000 TIME STEPS. GRADIENTS ARE COMPUTED THREE GRIDS IN AND 
!C           PROJECTED BACK TO OBTAIN NEW WATER LEVEL ELEVATIONS OR HEAD        ELEVATIONS AT BOUNDARIES.
!C
!C
      DIMENSION H(NR,NC), HT (NR,NC), HP(NR,NC), DX(NR,NC), DY (NR,NC)
!C
      IF ((I/2*2).NE.I) RETURN
!C
      NR1=NR-1
      NC1=NC-1
!C
      DO 120 I2=2,NC1
      IF (H(1,I2) .GE. 30000.0) GO TO 110
      IF (H(1,I2) .LT. 20000.0) GO TO 110
      DITP= (HT (2,I2)-HT (3,I2))* (DY(1,I2)+ DY(2,I2))/(DY (2, I2)+DY(3,I2))

      HT (1,I2)=HT (2,I2)+DITP 
 110  IF (H(NR,I2).GE.30000.0) GO TO 120
      IF (H(NR,I2).LT.20000.0) GO TO 120
      DIBT= (HT(NR-2,I2)-HT (NR-1,I2)) *(DY (NR, I2)+DY (NR-1,I2))/(DY(NR-2,I2 )+DY (NR-1,I2))
      HT (NR,I2)=HT(NR1,I2)-DIBT
 120  CONTINUE
!C
      DO 140 I1=2, NR1
      IF (H(I1,1).GE.30000.0) GO TO 130
      IF (H(I1,1).LT.20000.0) GO TO 130
      DILT =(HT(I1,2)-HT (I1, 3))*( DX(I1,1) +DX (I1,2))/(DX (I1,2)+DX (I1,3))
      HT(I1,1)=HT(I1,2)+DILT
 130  IF (H(I1,NC).GE.30000.0) GO TO 140
      IF (H(I1,NC).LT.20000.0) GO TO 140
      DIRT= (HT(I1, NC-2)-HT (I1,NC-1))*  (DX(I1,NC) +DX (I1, NC-1))/(DX(I1,NC-2)+DX (I1,NC-1))
      HT(I1,NC)=HT(I1,NC1)-DIRT
 140  CONTINUE
!C
      RETURN
!C
      END


!CSUBROUTINE BSOLVE

      SUBROUTINE BSOLVE (D,N,M,V)
!!C
!C         THIS SUEROUTINE SOLVES THE MATRIX, SET UP IN MATSOL, BY GAUSS 
!C        ELIMINATION.
!C  
      DIMENSION  D(N,M), V(N)
!C
      LR= (M-1)/2 
      DO 120  L=1,LR
      IM=LR-L+1
      DO 120 I=1,IM
      DO 110 J=2,M
 110  D(L, J-1)=D (L,J)
      KN=N-L
      KM=M-I
      D(L,M)=0.0
 120  D(KN+1,KM+1)=0.0
      LR=LR+1
      IM=N-1
      DO 190 I=1,IM
      NPIV=I
      LS= I+1
      DO 130 L=LS,LR
      IF (ABS(D(L, 1)).GT.ABS(D(NPIV,1))) NPIV=L
 130  CONTINUE
      IF (NPIV.LE.I) GO TO 150
      DO 140 J=1,M
      TEMP=D(I,J)
      D(I, J) =D(NPIV,J)

 140  D(NPIV,J)=TEMP
      TEMP=V(I)
      V(I)=V(NPIV)
      V(NPIV)=TEMP
 150  V(I)=V(I)/D(I,1)
      DO 160 J=2,M
 160  D(I,J)=D(I,J)/D(I,1)
      DO 180 L=LS,LR
      TEMP = D(L,1)
      V(L)=V(L)-TEMP*V(I)
      DO  170 J=2,M
 170  D(L,J-1)=D(L,J)-TEMP*D(I,J)
 180  D(L,M)=0.0
      IF(LR.LT.N)  LR=LR+1
 190  CONTINUE
      V(N)=V(N)/D(N,1)
      JM=2
      DO 210 I=1,JM
      L=N-1
      DO 200 J=2,JM
      KM=L+J
 200  V(L)=V(L)-D(L,J)*V(KM-1)
      IF (JM.LT. M)     JM=JM+1
 210  CONTINUE
      !C
      RETURN
      !C
      END


